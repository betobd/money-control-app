// Generates src/features/currency/currency-names.generated.ts: every supported
// currency's display name in each interface language, from Node's ICU data.
// Run manually after the registry changes; the output is committed.
//
//   node scripts/generate-currency-names.mjs
//
// Hermes does not reliably ship Intl.DisplayNames, so the names are resolved here
// at build time rather than on the device.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registryPath = resolve(root, 'src/features/currency/currency-registry.ts');
const outputPath = resolve(root, 'src/features/currency/currency-names.generated.ts');

// Interface language -> the Intl locale whose names it shows. Mirrors
// src/i18n/languages.ts.
const LOCALES = {
  en: 'en-US',
  es: 'es-ES',
  pt: 'pt-BR',
  fr: 'fr-FR',
  de: 'de-DE',
  it: 'it-IT',
};

const registry = readFileSync(registryPath, 'utf8');
const match = /export const supportedCurrencyCodes = \[([^\]]*)\] as const;/.exec(registry);
if (!match) throw new Error(`Could not find supportedCurrencyCodes in ${registryPath}`);
const codes = [...match[1].matchAll(/'([A-Z]{3})'/g)].map((entry) => entry[1]);
if (codes.length === 0) throw new Error('supportedCurrencyCodes is empty');

/** Upper-cases the first letter for list display: "peso colombiano" -> "Peso colombiano". */
function capitalizeFirst(text, locale) {
  return text.charAt(0).toLocaleUpperCase(locale) + text.slice(1);
}

const sections = [];
const missing = {};
for (const [language, locale] of Object.entries(LOCALES)) {
  // `fallback: 'none'` returns undefined instead of echoing the code, so a code ICU
  // cannot name is omitted and the accessor falls back to the registry name.
  const names = new Intl.DisplayNames(locale, { type: 'currency', fallback: 'none' });
  const lines = [];
  for (const code of codes) {
    const name = names.of(code);
    if (!name || name === code) {
      (missing[language] ??= []).push(code);
      continue;
    }
    lines.push(`    ${code}: ${JSON.stringify(capitalizeFirst(name, locale))},`);
  }
  sections.push(`  ${language}: {\n${lines.join('\n')}\n  },`);
}

const file = `/**
 * Currency names per interface language. Generated by
 * scripts/generate-currency-names.mjs from Node's full ICU data; do not edit.
 */
import type { Language } from '@/i18n/languages';
import type { CurrencyCode } from './currency-registry';

export const localizedCurrencyNames: Partial<Record<Language, Partial<Record<CurrencyCode, string>>>> = {
${sections.join('\n')}
};
`;

writeFileSync(outputPath, file, 'utf8');
console.log('ICU', process.versions.icu, '-', codes.length, 'currencies');
console.log('without an ICU name (registry fallback):', missing);
console.log('wrote', outputPath);
